import { randomBytes } from 'node:crypto';
import { chmod, open, readFile, rename, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnvironment } from './env.js';

export const EXTERNAL_SETUP_FIELDS = Object.freeze([
  'DISCORD_BOT_TOKEN',
  'DISCORD_CLIENT_ID',
  'DISCORD_GUILD_ID',
  'OWNER_ID',
  'DATABASE_POOL_URL',
  'DATABASE_DIRECT_URL',
]);

const GENERATED_FIELDS = Object.freeze([
  'STATUS_TOKEN',
  'DATA_ENCRYPTION_KEYS_JSON',
  'VOUCHER_HMAC_KEYS_JSON',
]);

const SETUP_ONLY_FIELDS = Object.freeze(['DATABASE_SSL_CA_INPUT', 'DATABASE_SSL_CA_PATH']);
const OPTIONAL_RUNTIME_FIELDS = Object.freeze([
  'NODE_ENV', 'PORT', 'TIMEZONE', 'PRELAUNCH', 'BACKUP_MODE', 'BACKUP_ENABLED',
  'DATABASE_BACKUP_URL', 'DATABASE_RESTORE_URL', 'PG_DUMP_PATH', 'PG_RESTORE_PATH',
  'S3_ENDPOINT', 'S3_REGION', 'S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY',
  'S3_FORCE_PATH_STYLE', 'RUNNER_CONCURRENCY', 'RUNNER_CONCURRENCY_HARD_MAX', 'GIT_SHA',
  'DISCORD_CLIENT_VERSION', 'DISCORD_CHROME_VERSION', 'DISCORD_ELECTRON_VERSION',
  'DISCORD_BUILD_NUMBER', 'DISCORD_NATIVE_BUILD_NUMBER', 'DISCORD_LOCALE',
]);
const ENVIRONMENT_LINE = /^(?:export\s+)?([A-Z][A-Z0-9_]*)=(.*)$/;
const ENVIRONMENT_ASSIGNMENT = /^(\s*(?:export\s+)?)([A-Z][A-Z0-9_]*)(\s*=).*$/;

function unquote(value) {
  if (value.length < 2) return value;
  const first = value.at(0);
  const last = value.at(-1);
  if ((first === "'" && last === "'") || (first === '"' && last === '"')) {
    return value.slice(1, -1);
  }
  return value;
}

export function parseEnvironmentText(text) {
  const values = {};
  for (const rawLine of String(text ?? '').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = ENVIRONMENT_LINE.exec(line);
    if (match) values[match[1]] = unquote(match[2].trim());
  }
  return values;
}

function encodeEnvironmentValue(value) {
  const text = String(value);
  if (/^[A-Za-z0-9_./:@?=&%+,-]*$/.test(text)) return text;
  if (text.includes("'") || /[\r\n]/.test(text)) {
    throw new Error('Environment values must not contain quotes or newlines; URL-encode special characters');
  }
  return "'" + text + "'";
}

export function upsertEnvironmentText(original, updates) {
  const pending = new Map(Object.entries(updates));
  const lines = String(original ?? '').split(/\r?\n/).map((line) => {
    const match = ENVIRONMENT_ASSIGNMENT.exec(line);
    if (!match || !pending.has(match[2])) return line;
    const value = pending.get(match[2]);
    pending.delete(match[2]);
    return match[1] + match[2] + match[3] + encodeEnvironmentValue(value);
  });
  while (lines.length && lines.at(-1) === '') lines.pop();
  if (pending.size) {
    if (lines.length) lines.push('');
    lines.push('# Generated by npm run setup — keep these values stable and secret.');
    for (const [key, value] of pending) lines.push(key + '=' + encodeEnvironmentValue(value));
  }
  return lines.join('\n') + '\n';
}

function createKeyring(randomBytesFunction) {
  return JSON.stringify({ current: 1, keys: { 1: randomBytesFunction(32).toString('base64') } });
}

export function createAutomaticValues({ randomBytesFunction = randomBytes } = {}) {
  return {
    STATUS_TOKEN: randomBytesFunction(32).toString('hex'),
    DATA_ENCRYPTION_KEYS_JSON: createKeyring(randomBytesFunction),
    VOUCHER_HMAC_KEYS_JSON: createKeyring(randomBytesFunction),
  };
}

function looksLikeCertificate(value) {
  return String(value).includes('BEGIN CERTIFICATE');
}

function decodeCertificateBase64(value) {
  try {
    const decoded = Buffer.from(String(value), 'base64').toString('utf8');
    return looksLikeCertificate(decoded) ? String(value) : null;
  } catch {
    return null;
  }
}

export async function resolveCertificateBase64(input, { readFileFunction = readFile } = {}) {
  const value = String(input ?? '').trim();
  if (!value) throw new Error('DATABASE_SSL_CA is required as a PEM file path, PEM text, or Base64');
  if (looksLikeCertificate(value)) return Buffer.from(value, 'utf8').toString('base64');
  const encoded = decodeCertificateBase64(value);
  if (encoded) return encoded;
  try {
    const certificate = await readFileFunction(path.resolve(value), 'utf8');
    if (!looksLikeCertificate(certificate)) throw new Error('file is not a PEM certificate');
    return Buffer.from(certificate, 'utf8').toString('base64');
  } catch (error) {
    throw new Error('Cannot read PostgreSQL CA certificate: ' + error.message, { cause: error });
  }
}

function pickNonempty(...values) {
  return values.find((value) => value != null && String(value).trim() !== '');
}

function copyConfiguredValues(updates, effective, fileValues, fields) {
  for (const key of fields) {
    const value = pickNonempty(effective[key], fileValues[key]);
    if (value) updates[key] = value;
  }
}

function assertNoImplicitSecretRotation(key, fileValues, processValues) {
  if (pickNonempty(fileValues[key]) && pickNonempty(processValues[key])
    && fileValues[key] !== processValues[key]) {
    throw new Error(key + ' conflicts with the durable .env value; refusing implicit secret rotation');
  }
}

function populateGeneratedValues(updates, fileValues, processValues, randomBytesFunction) {
  let automatic;
  for (const key of GENERATED_FIELDS) {
    // Once generated into the durable file, local key material wins over an
    // accidental process-level override. Rotation is a separate audited flow.
    assertNoImplicitSecretRotation(key, fileValues, processValues);
    const existing = pickNonempty(fileValues[key], processValues[key]);
    automatic ??= existing ? null : createAutomaticValues({ randomBytesFunction });
    updates[key] = existing ?? automatic[key];
  }
}

async function populateCertificateValue(updates, effective, readFileFunction) {
  const certificateInput = pickNonempty(
    effective.DATABASE_SSL_CA_BASE64,
    effective.DATABASE_SSL_CA_INPUT,
    effective.DATABASE_SSL_CA_PATH,
  );
  if (certificateInput) {
    updates.DATABASE_SSL_CA_BASE64 = await resolveCertificateBase64(certificateInput, { readFileFunction });
  }
}

function finalizeSetupCandidate(fileValues, processValues, updates) {
  const candidate = { ...fileValues, ...processValues, ...updates };
  for (const key of SETUP_ONLY_FIELDS) delete candidate[key];
  const missing = [...EXTERNAL_SETUP_FIELDS].filter((key) => !pickNonempty(candidate[key]));
  return { candidate, missing };
}

export async function completeSetupValues({ fileValues = {}, processValues = process.env,
  randomBytesFunction = randomBytes, readFileFunction = readFile } = {}) {
  const effective = { ...fileValues, ...processValues };
  const updates = {};
  copyConfiguredValues(updates, effective, fileValues, EXTERNAL_SETUP_FIELDS);
  copyConfiguredValues(updates, effective, fileValues, OPTIONAL_RUNTIME_FIELDS);
  populateGeneratedValues(updates, fileValues, processValues, randomBytesFunction);
  await populateCertificateValue(updates, effective, readFileFunction);
  updates.BACKUP_MODE = pickNonempty(effective.BACKUP_MODE,
    effective.BACKUP_ENABLED === 'true' ? 'LOCAL_S3' : 'AIVEN_MANAGED');

  const { candidate, missing } = finalizeSetupCandidate(fileValues, processValues, updates);
  if (missing.length) return { candidate, generated: updates, missing, validated: null };
  const validated = loadEnvironment(candidate);
  return { candidate, generated: updates, missing: [], validated };
}

export async function writeEnvironmentFile(filePath, original, updates) {
  const target = filePath instanceof URL ? fileURLToPath(filePath) : path.resolve(filePath);
  const temporary = target + '.' + process.pid + '.tmp';
  const content = upsertEnvironmentText(original, updates);
  let handle;
  try {
    handle = await open(temporary, 'wx', 0o600);
    await handle.writeFile(content, 'utf8');
    await handle.sync();
    await handle.close();
    handle = null;
    await rename(temporary, target);
    await chmod(target, 0o600);
  } catch (error) {
    await handle?.close().catch(() => null);
    await unlink(temporary).catch(() => null);
    throw error;
  }
  // Do not return the serialized file.  Callers only need the durable path;
  // returning content makes accidental secret logging far too easy.
  return { path: target };
}
